# Лабораторная работа №5: Броуновское движение и геометрическое броуновское движение

# Параметры моделирования
delta = 0.0001  # Шаг дискретизации (sqrt(delta) = 0.01, как указано в задании)
k_max = 1000    # Количество шагов
n_points = k_max + 1  # Количество точек, включая начальную

# Задание 1: Обоснование свойств броуновского движения
cat("Обоснование свойств броуновского движения:\n")
cat("Процесс моделируется как B_{kΔ} = Σ ε_{iΔ}, где ε_{iΔ} ~ N(0, Δ), i = 1, ..., k.\n")
cat("1. Математическое ожидание: E[B_{kΔ}] = E[Σ ε_{iΔ}] = Σ E[ε_{iΔ}] = 0, так как E[ε_{iΔ}] = 0.\n")
cat("2. Дисперсия: E[B_{kΔ}^2] = E[(Σ ε_{iΔ})^2] = Σ E[ε_{iΔ}^2] = Σ Δ = kΔ, так как ε_{iΔ} независимы и E[ε_{iΔ}^2] = Δ.\n")
cat("3. Ковариация: E[B_{kΔ}B_{lΔ}] = E[(Σ_{i=1}^k ε_{iΔ})(Σ_{j=1}^l ε_{jΔ})] = Σ_{i=1}^min(k,l) E[ε_{iΔ}^2] = min(k,l)Δ.\n")
cat("4. Начальное условие: B_0 = 0 по определению.\n\n")

# Задание 2: Моделирование броуновского движения
cat("Моделирование броуновского движения по формуле:\n")
cat("B_{(k+1)Δ} = B_{kΔ} + ε_{(k+1)Δ}, где ε_{(k+1)Δ} ~ N(0, Δ)\n\n")

# Инициализация вектора для броуновского движения
B = numeric(n_points)
B[1] = 0  # Начальное условие B_0 = 0

# Генерация случайных приращений
noise = rnorm(n_points, mean = 0, sd = sqrt(delta))

# Вычисление траектории броуновского движения
for (k in 2:n_points) {
  B[k] = B[k - 1] + noise[k]
}

# Визуализация броуновского движения
plot(seq(0, k_max * delta, by = delta), B, type = "l",
     main = "Траектория броуновского движения",
     xlab = "Время, t",
     ylab = "B(t)",
     col = "darkgreen",
     lwd = 1.5)
grid()

# Задание 2: Моделирование геометрического броуновского движения
S0 = 100  # Начальное значение (из задания)
a = 0.5   # Параметр дрейфа (из задания)
sigma = 0.8  # Волатильность (из задания)

cat("Моделирование геометрического броуновского движения по формуле:\n")
cat("S_t = S_0 * exp((a - σ^2/2) * t + σ * B_t)\n\n")

# Инициализация вектора для геометрического броуновского движения
S = numeric(n_points)
S[1] = S0  # Начальное значение

# Вычисление траектории геометрического броуновского движения
for (k in 1:k_max) {
  t = k * delta
  S[k + 1] = S0 * exp((a - sigma^2 / 2) * t + sigma * B[k + 1])
}

# Визуализация геометрического броуновского движения
plot(seq(0, k_max * delta, by = delta), S, type = "l",
     main = "Геометрическое броуновское движение",
     xlab = "Время, t",
     ylab = "S(t)",
     col = "purple",
     lwd = 1.5)
grid()

