library(stats)

# Задание 1: Моделирование последовательности банковского счета {B_n}
N = 200          # Количество временных шагов
r = 0.01         # Процентная ставка
B = numeric(N + 1)  # Вектор для хранения значений B_n (от B_0 до B_200)
B[1] = 1         # Начальное значение B_0 = 1

# Вычисление значений B_n по формуле B_n = (1 + r) * B_{n-1}
for (n in 1:N) {
  B[n + 1] = B[n] * (1 + r)
}

# Построение графика банковского счета
plot(0:N, B, type = "l", col = "navy", 
     xlab = "n", ylab = "B_n", 
     main = "Динамика банковского счета")
cat("B_0:", B[1], "\n")
cat("B_200:", B[N + 1], "\n")

# Задание 2: Моделирование случайного процесса акций {S_n}
S_0 = 1          # Начальная цена акции
a = -0.3         # Нижняя доходность
b = 0.8          # Верхняя доходность
p = 0.4          # Вероятность роста (P(ρ_n = b))
S = numeric(N + 1)  # Вектор для хранения значений S_n
S[1] = S_0       # Начальное значение S_0 = 1

rho = rbinom(N, 1, p)  # Генерация бернуллиевских случайных величин
rho = ifelse(rho == 1, b, a)  # Преобразование: 1 → b, 0 → a

# Вычисление значений S_n
for (n in 1:N) {
  S[n + 1] = S[n] * (1 + rho[n])
}

# Построение графика траектории цены акции
plot(0:N, S, type = "l", col = "maroon", 
     xlab = "n", ylab = "S_n", 
     main = "Траектория цены акции")
cat("S_0:", S[1], "\n")
cat("S_200:", S[N + 1], "\n")

# Задание 3: Расчет справедливой цены call-опциона
S_0 = 100
N = 10
a = -0.3
b = 0.8
r = 0.2
K = 100

# Вычисление \bar{p}
p_bar = (r - a) / (b - a)

# Вычисление p^*
p_star = ((1 + b) / (1 + r)) * p_bar

# Вычисление K_0
ln_term = log(K / (S_0 * (1 + a)^N))
ln_ratio = log((1 + b) / (1 + a))
K_0 = 1 + floor(ln_term / ln_ratio)

# Расчет справедливой цены call-опциона C_N
if (K_0 > N) {
  C_N = 0
} else {
  # Вычисление B(K_0, N; p^*) — хвост биномиального распределения
  B_p_star = 1 - pbinom(K_0 - 1, N, p_star)
  
  # Вычисление B(K_0, N; \bar{p})
  B_p_bar = 1 - pbinom(K_0 - 1, N, p_bar)
  
  # Формула справедливой цены
  C_N = S_0 * B_p_star - K * (1 + r)^(-N) * B_p_bar
}

# Вывод результата с округлением до 4 знаков
cat("Справедливая цена call-опциона:", round(C_N, 4), "\n")

